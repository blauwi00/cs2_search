import type { Currency } from '../types/market.ts';
import { toKop, type FxRate } from '../currency/nbu.ts';
import { header, esc, money } from './postfmt.ts';

export type RubricKind = 'caseev' | 'story' | 'tracked';

/** 0 = воскресенье (Варшава). */
export function rubricFor(weekday: number): RubricKind {
  return weekday === 1 || weekday === 4 ? 'caseev' : weekday === 6 ? 'tracked' : 'story';
}

// ---------- «Окупается ли кейс» ----------

export interface CaseEV {
  name: string; img: string | null; caseCents: number; keyCents: number;
  evCents: number; evNetCents: number; pWin: number; best: { name: string; cents: number; p: number };
}

/** Шанс как «примерно 1 из N». */
export function oneIn(p: number): string {
  if (p <= 0) return 'почти никогда';
  const n = 1 / p;
  const r = n < 10 ? Math.round(n * 10) / 10 : n < 100 ? Math.round(n) : n < 1000 ? Math.round(n / 10) * 10 : Math.round(n / 100) * 100;
  return `1 из ${String(r).replace('.', ',').replace(/\B(?=(\d{3})+(?!\d))/g, ' ')}`;
}

/** Кейс для поста: по очереди, без повторов из недавних; данные не старше 2 суток. */
export function pickCaseEV(list: CaseEV[], recent: string[]): CaseEV | null {
  return list.find((c) => !recent.includes(c.name)) ?? null;
}

export function caseEvPost(c: CaseEV, fx: Map<Currency, FxRate>, now: number): string {
  void now;
  const usd = fx.get('USD') ?? null;
  const k = (cents: number) => (usd ? toKop(cents, 'USD', usd) : null);
  const cost = c.caseCents + c.keyCents;
  const back = Math.round((c.evNetCents * 100) / cost);
  const verdict = back >= 100 ? 'В среднем окупается, но только в среднем, на большом числе открытий.'
    : back >= 70 ? 'В среднем не окупается, но теряешь немного.'
      : 'В среднем открытие минус. Если нужен скин из кейса, обычно дешевле купить его сразу.';
  // Крючок первой строкой с главной цифрой, 4 коротких строки, вывод одной фразой, сноска одной строкой.
  return [
    `<b>${esc(c.name)}: в среднем возвращает ${back}% потраченного</b>`, '',
    `Открыть: <b>${money(k(cost))}</b> (кейс ${money(k(c.caseCents))} + ключ ${money(k(c.keyCents))})`,
    `В среднем выпадает на: <b>${money(k(c.evNetCents))}</b> после комиссии Steam`,
    `Предмет дороже открытия: примерно <b>${oneIn(c.pWin)}</b>`,
    `Рекорд: ${esc(c.best.name)}, шанс ${oneIn(c.best.p)}`,
    '', verdict, '',
    '<i>Шансы опубликованы Valve, цены — средние продажи Steam.</i>',
  ].join('\n');
}

// ---------- «Что отслеживают в Ценолове» ----------

export const TRACKED_MIN_USERS = 3; // меньше — не показываем: и неинтересно, и можно узнать конкретного человека

export function trackedPost(rows: { name: string; n: number }[], totalUsers: number, now: number): string | null {
  const top = rows.filter((r) => r.n >= TRACKED_MIN_USERS).slice(0, 7);
  if (top.length < 3) return null;
  return [
    header('👀', 'Что отслеживают в Ценолове', now), '',
    ...top.map((r, i) => `${i + 1}. <b>${esc(r.name)}</b> — у ${r.n} чел.`), '',
    `Всего следят за ценами: ${totalUsers} чел.`,
    '<i>Без имён — только сколько человек добавили предмет в наблюдение или инвентарь. Хочешь получать уведомления по своим предметам — жми кнопку ниже.</i>',
  ].join('\n');
}

